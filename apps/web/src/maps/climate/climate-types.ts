export type ClimateBand = 'arctic' | 'cold' | 'temperate' | 'warm' | 'hot';

export type WhittakerBiome =
  | 'snow'
  | 'autumn'
  | 'desert'
  | 'dark_land'
  | 'rocky_highland'
  | 'wetland'
  | 'forest'
  | 'meadow';

export type ClimateAnchorKind = 'snow' | 'desert' | 'autumn' | 'dark_land' | 'rocky_highland';

/**
 * Soft climate attractor placed on eligible continental interior regions.
 * Pulls baseline temperature and moisture gradually via distance-based lerp
 * instead of hard-overwriting biome masks.
 */
export interface ClimateAnchor {
  readonly kind: ClimateAnchorKind;
  /** Source-space X coordinate in world tiles. */
  readonly sourceGX: number;
  /** Source-space Y coordinate in world tiles. */
  readonly sourceGY: number;
  /** Target temperature pulled toward by lerp (0..1). */
  readonly targetTemperature: number;
  /** Target moisture pulled toward by lerp (0..1). */
  readonly targetMoisture: number;
  /** Influence radius in world tiles. */
  readonly radius: number;
  /** Maximum lerp weight (0..1) at the anchor center. */
  readonly maxInfluence: number;
}

export interface ClimateContextOptions {
  /** Normalized elevation (0..1) cooling local temperature. */
  readonly elevation?: number;
  /** Normalized continentality (0 = coast/ocean, 1 = deep inland). */
  readonly continentality?: number;
  /** Whether the tile is near a freshwater river or lake. */
  readonly nearFreshwater?: boolean;
  /** Soft climate attractors generated by the macro continent plan. */
  readonly anchors?: readonly ClimateAnchor[];
}

export interface ClimateSample {
  /** Stable baseline temperature derived from seed, coordinates, and soft anchors. */
  temperature: number;
  /** Stable surface moisture derived from seed, coordinates, and soft anchors. */
  moisture: number;
  /** Stable atmospheric humidity derived from seed and world coordinates. */
  humidity: number;
  /** Elevation influence supplied by the terrain field. */
  elevation: number;
  /** Continentality influence (0 = coastal, 1 = deep continental interior). */
  continentality?: number;
  climateBand: ClimateBand;
  /** Primary Whittaker visual biome classification before regional border noise. */
  whittakerBiome?: WhittakerBiome;
}

